"""对比当前 config 和 STPoints 手动标定的重投影误差"""
import numpy as np

# ── 用户提供的 4 组 3D-2D 对应点 ──────────────────────────────
pts_3d = np.array([
    [2.289595194362603, -0.9745866327235891, 0.20226034558609818],
    [2.1475100799436078, -0.9586918181806363, 0.9459349529405053],
    [2.4809528545745754, -0.176392873507757, 0.9929215755807657],
    [2.6230379689935712, -0.19228768805070984, 0.24924696822635845],
])

pts_2d_gt = np.array([
    [126.47619047619047, 179.8095238095238],
    [131.04761904761904, 333.7142857142857],
    [303.23809523809524, 327.61904761904765],
    [295.61904761904765, 178.28571428571428],
])

# ── 相机内参（相同） ──────────────────────────────────────────
fx, fy = 523.08215322, 523.60224492
cx, cy = 327.81872513, 209.38830507

def project(extrinsic, pts_3d):
    """投影 3D 点到 2D"""
    R = extrinsic[:3, :3]
    t = extrinsic[:3, 3]
    cam = (R @ pts_3d.T).T + t  # [N, 3]
    u = fx * cam[:, 0] / cam[:, 2] + cx
    v = fy * cam[:, 1] / cam[:, 2] + cy
    return np.column_stack([u, v]), cam

def reproj_error(pts_2d_proj, pts_2d_gt):
    return np.sqrt(np.mean(np.sum((pts_2d_proj - pts_2d_gt) ** 2, axis=1)))

# ── 当前 config 外参 ──────────────────────────────────────────
ext_current = np.array([
    [ 0.13934028,  0.98174871,  0.12943627, -0.43472904],
    [ 0.07494091, -0.14079125,  0.98719891, -0.64239460],
    [ 0.98740475, -0.12785650, -0.09319103,  0.19974812],
    [ 0.00000000,  0.00000000,  0.00000000,  1.00000000],
])

# ── 用户 STPoints 手动求解的外参 ─────────────────────────────
ext_stpoints = np.array([
    [0.2168322955754322,  0.9707501829262537,  0.10309140577241738, -0.5756415016856624],
    [0.07116438151512233, -0.12104127620380822, 0.9900932482642852,  -0.6191771041605205],
    [0.9736115171869416,  -0.2073477557235628,  -0.09532849415229039, 0.019176556590038363],
    [0,                   0,                    0,                    1],
])

print("=" * 65)
print("重投影对比: 当前 config vs STPoints 手动标定")
print("=" * 65)

for name, ext in [("当前 config", ext_current), ("STPoints 手动标定", ext_stpoints)]:
    proj, cam_pts = project(ext, pts_3d)
    error = reproj_error(proj, pts_2d_gt)
    print(f"\n── {name} ──")
    print(f"  RMSE: {error:.2f} px")
    print(f"  3D点 → 投影2D点        (用户拖拽2D点)      误差")
    for i, (p3d, p2d_proj, p2d_gt) in enumerate(zip(pts_3d, proj, pts_2d_gt)):
        err = np.linalg.norm(p2d_proj - p2d_gt)
        print(f"  {i}: ({p2d_proj[0]:7.1f}, {p2d_proj[1]:7.1f})  vs  ({p2d_gt[0]:.1f}, {p2d_gt[1]:.1f})  err={err:.1f}px")

    print("\n  相机坐标系中的点 (X, Y, Z):")
    for i, cp in enumerate(cam_pts):
        behind = " [BEHIND CAMERA!]" if cp[2] <= 0 else ""
        print(f"  {i}: ({cp[0]:.3f}, {cp[1]:.3f}, {cp[2]:.3f}){behind}")
